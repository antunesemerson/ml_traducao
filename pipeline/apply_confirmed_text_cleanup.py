ACCENT_CHARS = "çãõéíóúâêô"
WORD_BOUNDARY_CHARS = r"\wÀ-ÿ"


def uses_word_boundaries(source: str) -> bool:
    plain = source.replace("?", "")
    for char in ACCENT_CHARS:
        plain = plain.replace(char, "")
    return plain.isalnum()


COMPILED_REPLACEMENTS = [
    (
        source,
        replacement,
        re.compile(rf"(?<![{WORD_BOUNDARY_CHARS}]){re.escape(source)}(?![{WORD_BOUNDARY_CHARS}])")
        if uses_word_boundaries(source)
        else None,
    )
    for source, replacement in SAFE_REPLACEMENTS.items()
]


def cleanup_text(text: str) -> tuple[str, Counter[str]]:
    updated = text
    hits: Counter[str] = Counter()
    for source, replacement, pattern in COMPILED_REPLACEMENTS:
        if source not in updated:
            continue
        if pattern:
            updated, count = pattern.subn(replacement, updated)
        else:
            count = updated.count(source)
            if count:
                updated = updated.replace(source, replacement)
        if count:
            hits[source] += count
    return updated, hits


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Clean safe mojibake fragments in confirmed texts.")
    parser.add_argument("--apply", action="store_true", help="Persist cleanup changes.")
    parser.add_argument("--limit", type=int, default=50, help="Preview limit.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    started = datetime.now()
    print("[apply_confirmed_text_cleanup] Starting confirmed text cleanup")
    print(f"[apply_confirmed_text_cleanup] Rule version: {RULE_VERSION}")
    print(f"[apply_confirmed_text_cleanup] Apply: {args.apply}")

    conn = db.connect()
    rows = conn.execute(
        """
        SELECT id, segment_id, confirmed_text
        FROM segment_confirmations
        WHERE confirmed_text LIKE '%?%'
        ORDER BY segment_id
        """
    ).fetchall()

    changed = []
    total_hits: Counter[str] = Counter()
    for row in rows:
        updated, hits = cleanup_text(row["confirmed_text"])
        if updated == row["confirmed_text"]:
            continue
        changed.append((row, updated, hits))
        total_hits.update(hits)

    if args.apply and changed:
        now = datetime.now().isoformat(timespec="seconds")
        for row, updated, _hits in changed:
            conn.execute(
                """
                UPDATE segment_confirmations
                SET confirmed_text = ?,
                    confirmation_source = CASE
                        WHEN confirmation_source LIKE '%manual_mojibake_cleanup%' THEN confirmation_source
                        ELSE confirmation_source || '+manual_mojibake_cleanup'
                    END,
                    updated_at = ?
                WHERE id = ?
                """,
                (updated, now, row["id"]),
            )
        conn.commit()

    lines = [
        "Confirmed text cleanup report",
        f"Started at: {started.isoformat(timespec='seconds')}",
        f"Elapsed: {datetime.now() - started}",
        f"Rule version: {RULE_VERSION}",
        f"Apply: {args.apply}",
        "",
        "Summary:",
        f"- Confirmations scanned with question mark: {len(rows)}",
        f"- Confirmations changed: {len(changed)}",
        f"- Applied changes: {len(changed) if args.apply else 0}",
        "",
        "Top replacements:",
    ]
    for source, count in total_hits.most_common(30):
        lines.append(f"- {source} -> {SAFE_REPLACEMENTS[source]}: {count}")
    lines.extend(["", "Preview:"])
    for row, updated, hits in changed[: args.limit]:
        lines.append(f"- segment {row['segment_id']} | hits: {dict(hits)}")
        lines.append(f"  before: {row['confirmed_text'][:240]}")
        lines.append(f"  after:  {updated[:240]}")

    settings = db.load_settings()
    report_path = db.write_report(settings, "apply_confirmed_text_cleanup", lines)
    log_path = db.write_log(settings, "apply_confirmed_text_cleanup", lines)
    print(f"[apply_confirmed_text_cleanup] Confirmations scanned with question mark: {len(rows)}")
    print(f"[apply_confirmed_text_cleanup] Confirmations changed: {len(changed)}")
    print(f"[apply_confirmed_text_cleanup] Applied changes: {len(changed) if args.apply else 0}")
    print(f"[apply_confirmed_text_cleanup] Report: {report_path}")
    print(f"[apply_confirmed_text_cleanup] Log: {log_path}")
    print("[apply_confirmed_text_cleanup] Done")


if __name__ == "__main__":
    main()
